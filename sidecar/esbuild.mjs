// Builds dist/: the bundled sidecar (main.js) plus what the extension
// reads from its extensionPath at runtime.
//
//   dist/main.js              src/main.ts + the vscode shim + mnemographica/src
//   dist/package.json         mnemographica/package.json (contributes, version)
//   dist/media/               mnemographica/media (webview.js/css, icons)
//   dist/out/src/models/*.js  stubs the topologica bootstrap require()s; each
//                             returns the model module bundled in main.js
//   dist/node_modules/        packages the extension resolves by path at
//                             runtime (require.resolve, a spawned CLI), with
//                             their production dependencies
//
// Usage: node esbuild.mjs [--watch]
import * as esbuild from 'esbuild';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const upstream = resolve(here, '..', 'mnemographica');
const modelsDir = join(upstream, 'src', 'models');
const dist = join(here, 'dist');
const nodeModules = join(here, 'node_modules');
const watch = process.argv.includes('--watch');

// Resolved with require.resolve / spawned by path inside the extension —
// esbuild cannot bundle those, so they ship as real packages
const RUNTIME_PACKAGES = ['@mnemonica/lethe', '@mnemonica/strategy'];

const toPosix = (value) => value.split(sep).join('/');

const listModels = (dir) => readdirSync(dir).flatMap((name) => {
	const full = join(dir, name);
	if (statSync(full).isDirectory()) {
		return listModels(full);
	}
	return /\.ts$/.test(name) && !name.endsWith('.d.ts') ? [full] : [];
});

const modelName = (file) => toPosix(relative(modelsDir, file)).replace(/\.ts$/, '');

/** `mnemographica:models` → { "<name>": () => require("<abs path>") } */
const modelsPlugin = {
	name: 'mnemographica-models',
	setup (build) {
		build.onResolve({ filter: /^mnemographica:models$/ }, (args) => ({ path: args.path, namespace: 'mnemographica-models' }));
		build.onLoad({ filter: /.*/, namespace: 'mnemographica-models' }, () => {
			const files = listModels(modelsDir);
			const entries = files.map(file => `\t${JSON.stringify(modelName(file))}: () => require(${JSON.stringify(file)})`);
			return {
				contents: `module.exports.models = {\n${entries.join(',\n')}\n};\n`,
				loader: 'js',
				resolveDir: modelsDir,
				watchFiles: files,
				watchDirs: [modelsDir]
			};
		});
	}
};

/**
 * Upstream compiles to CommonJS (tsc, module: commonjs), so every
 * `import` / `await import()` in mnemographica/src is a require() at
 * runtime and picks a package's "require" export. esbuild would pick
 * "import" instead — ws's ESM wrapper lacks ws.Server, dive has separate
 * ESM/CJS builds. Bare imports from upstream files resolve as require().
 */
const upstreamCommonJsPlugin = {
	name: 'upstream-commonjs-resolution',
	setup (build) {
		build.onResolve({ filter: /^[^./]/ }, async (args) => {
			const fromUpstream = args.importer.startsWith(upstream + sep);
			const isImport = args.kind === 'import-statement' || args.kind === 'dynamic-import';
			if (!fromUpstream || !isImport || args.pluginData?.asRequire || args.path === 'vscode' || args.path.startsWith('~')) {
				return undefined;
			}
			const result = await build.resolve(args.path, { kind: 'require-call', importer: args.importer, resolveDir: args.resolveDir, pluginData: { asRequire: true } });
			return result.errors.length > 0 ? undefined : result;
		});
	}
};

const writeModelStubs = () => {
	const stubsDir = join(dist, 'out', 'src', 'models');
	rmSync(stubsDir, { recursive: true, force: true });
	for (const file of listModels(modelsDir)) {
		const name = modelName(file);
		const stub = join(stubsDir, `${name}.js`);
		mkdirSync(dirname(stub), { recursive: true });
		writeFileSync(stub, `'use strict';\n// GENERATED by sidecar/esbuild.mjs: the model is bundled in main.js\nmodule.exports = globalThis.__mnemographicaSidecarModels(${JSON.stringify(name)});\n`);
	}
};

// Node resolution of `name` as seen from `fromDir`
const findPackageDir = (name, fromDir) => {
	for (let dir = fromDir; ; dir = dirname(dir)) {
		const candidate = join(dir, 'node_modules', name);
		if (existsSync(join(candidate, 'package.json'))) {
			return candidate;
		}
		if (dirname(dir) === dir) {
			return undefined;
		}
	}
};

const copyRuntimePackages = () => {
	const target = join(dist, 'node_modules');
	rmSync(target, { recursive: true, force: true });
	const seen = new Set();
	const queue = RUNTIME_PACKAGES.map(name => ({ name, from: here, optional: false }));
	while (queue.length > 0) {
		const { name, from, optional } = queue.shift();
		const dir = findPackageDir(name, from);
		if (!dir) {
			if (optional) {
				continue;
			}
			throw new Error(`runtime package ${name} not installed (needed from ${from})`);
		}
		if (seen.has(dir)) {
			continue;
		}
		seen.add(dir);
		cpSync(dir, join(target, relative(nodeModules, dir)), { recursive: true, dereference: true });
		const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
		for (const dep of Object.keys(manifest.dependencies ?? {})) {
			queue.push({ name: dep, from: dir, optional: false });
		}
		for (const dep of Object.keys(manifest.optionalDependencies ?? {})) {
			queue.push({ name: dep, from: dir, optional: true });
		}
	}
	return seen.size;
};

const copyExtensionFiles = () => {
	rmSync(join(dist, 'media'), { recursive: true, force: true });
	cpSync(join(upstream, 'media'), join(dist, 'media'), { recursive: true });
	cpSync(join(upstream, 'package.json'), join(dist, 'package.json'));
	writeModelStubs();
};

/** @type {import('esbuild').BuildOptions} */
const options = {
	absWorkingDir: here,
	entryPoints: ['src/main.ts'],
	outfile: 'dist/main.js',
	bundle: true,
	platform: 'node',
	format: 'cjs',
	target: 'node18',
	sourcemap: 'linked',
	// the shim IS `vscode`
	alias: { vscode: './src/shim/index.ts' },
	nodePaths: [nodeModules],
	resolveExtensions: ['.ts', '.js', '.mjs', '.cjs', '.json'],
	// ws's optional native accelerators: absent → ws falls back to JS
	// The package.json lookups stay runtime require.resolve calls (→ dist/node_modules).
	external: ['bufferutil', 'utf-8-validate', ...RUNTIME_PACKAGES.map(name => `${name}/package.json`)],
	plugins: [modelsPlugin, upstreamCommonJsPlugin],
	logLevel: 'warning',
	logOverride: {
		// appChannelClient require()s ws-session.js by computed path (dist/node_modules)
		'unsupported-require-call': 'silent'
	}
};

if (watch) {
	copyExtensionFiles();
	copyRuntimePackages();
	const ctx = await esbuild.context(options);
	await ctx.watch();
	console.log('watching src/ and ../mnemographica/src …');
} else {
	mkdirSync(dist, { recursive: true });
	const result = await esbuild.build({ ...options, metafile: true });
	copyExtensionFiles();
	const packages = copyRuntimePackages();
	const bytes = statSync(join(dist, 'main.js')).size;
	console.log(`dist/main.js ${(bytes / 1024).toFixed(0)} KB, ${Object.keys(result.metafile.inputs).length} inputs; ${packages} runtime packages in dist/node_modules`);
}
