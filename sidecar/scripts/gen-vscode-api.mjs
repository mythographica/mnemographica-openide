// Re-publishes @types/vscode under the module name 'vscode-api'.
//
// The shim IS the 'vscode' module (tsconfig paths + esbuild alias), so the
// real API declarations need a second name for the shim to implement and
// `satisfies`-check against. @types/vscode is one ambient
// `declare module 'vscode' { … }` block plus the global Thenable; only the
// module name changes. The output is generated (gitignored), never edited.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const source = require.resolve('@types/vscode/index.d.ts');
const text = readFileSync(source, 'utf8');
const marker = "declare module 'vscode' {";
if (!text.includes(marker)) {
	throw new Error(`${source}: '${marker}' not found — @types/vscode layout changed`);
}
const version = require('@types/vscode/package.json').version;
const out = join(here, '..', 'src', 'shim', 'generated', 'vscode-api.d.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// GENERATED by scripts/gen-vscode-api.mjs from @types/vscode@${version} — do not edit\n`
	+ text.replace(marker, "declare module 'vscode-api' {"));
console.log(`vscode-api.d.ts <- @types/vscode@${version}`);
